/*
 * Generic vocabulary builder for a target language.
 *
 *   node scripts/build-lang-vocab.js <code>
 *
 * Reads content/<code>/source.tsv (tab-separated, header required) and writes
 * data/<code>/vocab.js in the multi-language deck contract. Zero dependencies,
 * deterministic output.
 *
 * Source columns (exact order):
 *   rank  word  reading  pos  english  example  example_english
 *
 * Rules (learned from the Japanese pipeline bugs, see tickets T-003/T-027):
 *   - field aware: TSV, so no comma escaping needed; tabs/newlines forbidden
 *   - dedupe by `word`
 *   - drop symbol-only / letter-less rows
 *   - no silent truncation: log the omitted count
 *   - stable ids (<code>-0001) so SRS progress survives rebuilds (T-061)
 */
const fs = require('fs');
const path = require('path');

const code = (process.argv[2] || '').trim();
if (!code) {
  console.error('Usage: node scripts/build-lang-vocab.js <code>   (e.g. es, fr, ko, zh)');
  process.exit(1);
}
if (!/^[a-z]{2}$/.test(code)) {
  console.error('Invalid language code "' + code + '" (expected two lowercase letters).');
  process.exit(1);
}

const root = process.cwd();
const srcPath = path.join(root, 'content', code, 'source.tsv');
const outPath = path.join(root, 'data', code, 'vocab.js');

if (!fs.existsSync(srcPath)) {
  console.error('Missing source file: content/' + code + '/source.tsv');
  process.exit(1);
}

const REQUIRED = ['rank', 'word', 'reading', 'pos', 'english', 'example', 'example_english'];
const raw = fs.readFileSync(srcPath, 'utf8').replace(/^\uFEFF/, '');
const lines = raw.split(/\r?\n/).filter(function (l) { return l.trim().length > 0; });
if (lines.length < 2) {
  console.error('content/' + code + '/source.tsv has no data rows.');
  process.exit(1);
}

const header = lines[0].split('\t').map(function (h) { return h.trim(); });
const missing = REQUIRED.filter(function (c) { return header.indexOf(c) === -1; });
if (missing.length) {
  console.error('Header mismatch. Missing columns: ' + missing.join(', ') + '. Expected: ' + REQUIRED.join(', '));
  process.exit(1);
}
const idx = {};
REQUIRED.forEach(function (c) { idx[c] = header.indexOf(c); });

const seen = {};
const words = [];
let skippedDup = 0;
let skippedBad = 0;

for (let i = 1; i < lines.length; i++) {
  const parts = lines[i].split('\t');
  if (parts.length < REQUIRED.length) {
    skippedBad++;
    console.warn('Row ' + (i + 1) + ': expected ' + REQUIRED.length + ' columns, got ' + parts.length + '. Skipped.');
    continue;
  }
  const get = function (c) { return (parts[idx[c]] || '').trim(); };
  const w = get('word');
  if (!w) { skippedBad++; continue; }
  if (!/[\p{L}]/u.test(w)) { skippedBad++; continue; } // symbol-only
  if (seen[w]) { skippedDup++; console.warn('Duplicate word "' + w + '" skipped.'); continue; }
  seen[w] = true;
  words.push({
    id: code + '-' + String(words.length + 1).padStart(4, '0'),
    w: w,
    p: get('reading'),
    d: get('english'),
    s: get('example') + (get('example_english') ? ' (' + get('example_english') + ')' : '')
  });
}

if (words.length === 0) {
  console.error('No valid words produced. Aborting.');
  process.exit(1);
}

const deck = {
  lang: code,
  version: 1,
  generatedAt: new Date().toISOString().slice(0, 10),
  words: words
};

const banner =
  '/*\n' +
  ' * Generated by scripts/build-lang-vocab.js from content/' + code + '/source.tsv.\n' +
  ' * Do not edit by hand; edit the source and rebuild.\n' +
  ' */\n';
const body =
  '(function () {\n' +
  '    var deck = ' + JSON.stringify(deck, null, 4).replace(/\n/g, '\n    ') + ';\n' +
  "    if (window.SqweaseVocab && window.SqweaseVocab.provide) window.SqweaseVocab.provide('" + code + "', deck);\n" +
  '    else window.SQWEASE_VOCAB = deck;\n' +
  '})();\n';

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, banner + body, 'utf8');

console.log('Wrote ' + words.length + ' words to data/' + code + '/vocab.js (skipped: ' + skippedDup + ' dup, ' + skippedBad + ' bad).');
